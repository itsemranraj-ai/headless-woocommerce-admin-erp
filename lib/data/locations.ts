/**
 * Returns country location data with states and cities sorted alphabetically (A–Z).
 */
export function getLocationData(countryCode: string): CountryLocationData {
  const loc = COUNTRY_LOCATIONS[countryCode.toUpperCase()];
  if (!loc) {
    return {
      name: countryCode,
      code: countryCode,
      states: [],
      cities: [],
    };
  }
  return {
    ...loc,
    states: [...loc.states].sort((a, b) => a.localeCompare(b)),
    cities: [...loc.cities].sort((a, b) => a.localeCompare(b)),
  };
}

/**
 * Returns city suggestions sorted alphabetically (A–Z) for a given country & state.
 */
export function getCitiesForState(countryCode: string, stateName: string): string[] {
  const loc = COUNTRY_LOCATIONS[countryCode.toUpperCase()];
  if (!loc) return [];
  if (stateName && loc.stateCities) {
    const clean = stateName.trim().toLowerCase();
    for (const [key, cities] of Object.entries(loc.stateCities)) {
      if (key.toLowerCase() === clean || clean.includes(key.toLowerCase()) || key.toLowerCase().includes(clean)) {
        return [...cities].sort((a, b) => a.localeCompare(b));
      }
    }
  }
  return [...loc.cities].sort((a, b) => a.localeCompare(b));
}

/**
 * Returns states matching a city sorted alphabetically (A–Z).
 */
export function getStatesForCity(countryCode: string, cityName: string): string[] {
  const loc = getLocationData(countryCode);
  if (!loc) return [];
  return [...loc.states].sort((a, b) => a.localeCompare(b));
}
